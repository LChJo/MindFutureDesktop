use serde::Serialize;
use std::fs;
use std::path::PathBuf;

const MARKER_BEGIN: &str = "# >>> MoontonClaudeDesktop aliases >>>";
const MARKER_END: &str = "# <<< MoontonClaudeDesktop aliases <<<";
const FILE_HEADER: &str = "# Claude aliases generated by Moonton Claude Desktop\n# Do not edit manually - this file is auto-generated\n";

#[derive(Serialize)]
pub struct SystemAliasesStatus {
    pub registered: bool,
    pub file_exists: bool,
    pub profile_has_source: bool,
    pub aliases_file_path: String,
    pub profile_path: String,
}

// --- Validation helpers (same logic as pty.rs) ---

fn is_valid_alias_name(name: &str) -> bool {
    if name.is_empty() {
        return false;
    }
    let first = name.chars().next().unwrap();
    first.is_ascii_alphabetic()
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
}

fn is_valid_env_key(key: &str) -> bool {
    if key.is_empty() {
        return false;
    }
    let first = key.chars().next().unwrap();
    (first.is_ascii_alphabetic() || first == '_')
        && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

// --- Escaping helpers (same logic as pty.rs) ---

/// Escape a string for use inside PowerShell double-quoted strings.
#[cfg(target_os = "windows")]
fn escape_powershell(s: &str) -> String {
    s.replace('`', "``")
        .replace('"', "`\"")
        .replace('$', "`$")
}

/// Escape a string for use inside zsh single-quoted strings.
#[cfg(target_os = "macos")]
fn escape_zsh_single_quote(s: &str) -> String {
    s.replace('\'', "'\\''")
}

// --- Path helpers ---

fn get_home_dir() -> Result<PathBuf, String> {
    dirs::home_dir().ok_or_else(|| "Failed to get home directory".to_string())
}

fn get_aliases_file_path() -> Result<PathBuf, String> {
    let home = get_home_dir()?;
    #[cfg(target_os = "windows")]
    {
        Ok(home
            .join(".MoontonClaudeDesktop")
            .join("claude-aliases.ps1"))
    }
    #[cfg(target_os = "macos")]
    {
        Ok(home
            .join(".MoontonClaudeDesktop")
            .join("claude-aliases.zsh"))
    }
}

fn get_shell_profile_path() -> Result<PathBuf, String> {
    let home = get_home_dir()?;
    #[cfg(target_os = "windows")]
    {
        Ok(home
            .join("Documents")
            .join("WindowsPowerShell")
            .join("Microsoft.PowerShell_profile.ps1"))
    }
    #[cfg(target_os = "macos")]
    {
        Ok(home.join(".zshrc"))
    }
}

// --- Alias content generation ---

#[cfg(target_os = "windows")]
fn generate_aliases_content(aliases: &[crate::ClaudeAliasConfig]) -> String {
    let mut content = String::from(FILE_HEADER);
    content.push('\n');

    for alias in aliases {
        if !is_valid_alias_name(&alias.name) {
            log::warn!("Skipping alias with invalid name: {}", alias.name);
            continue;
        }
        let mut env_setters = Vec::new();
        // Always inject the three Anthropic vars (even if empty) to prevent
        // inheriting stale system environment variables.
        {
            let model = alias.anthropic_model.as_deref().unwrap_or("");
            env_setters.push(format!(
                "$env:ANTHROPIC_MODEL=\"{}\"",
                escape_powershell(model)
            ));
        }
        {
            let token = alias.anthropic_auth_token.as_deref().unwrap_or("");
            env_setters.push(format!(
                "$env:ANTHROPIC_AUTH_TOKEN=\"{}\"",
                escape_powershell(token)
            ));
        }
        {
            let url = alias.anthropic_base_url.as_deref().unwrap_or("");
            env_setters.push(format!(
                "$env:ANTHROPIC_BASE_URL=\"{}\"",
                escape_powershell(url)
            ));
        }
        if let Some(ref custom_vars) = alias.custom_env_vars {
            for (k, v) in custom_vars {
                if !is_valid_env_key(k) {
                    log::warn!("Skipping custom env var with invalid key: {}", k);
                    continue;
                }
                if !v.is_empty() {
                    env_setters.push(format!("$env:{}=\"{}\"", k, escape_powershell(v)));
                }
            }
        }
        // Clear CLAUDECODE before AND after claude to prevent "nested session" detection.
        // Claude sets CLAUDECODE during execution; if not cleared after exit,
        // subsequent `claude` invocations in the same session will fail.
        let clear_nested = "$env:CLAUDECODE=$null";
        let func_body = if env_setters.is_empty() {
            format!("{}; claude @args; {}", clear_nested, clear_nested)
        } else {
            format!(
                "{}; {}; claude @args; {}",
                clear_nested,
                env_setters.join("; "),
                clear_nested
            )
        };
        content.push_str(&format!("function {} {{ {} }}\n", alias.name, func_body));
    }

    content
}

#[cfg(target_os = "macos")]
fn generate_aliases_content(aliases: &[crate::ClaudeAliasConfig]) -> String {
    let mut content = String::from(FILE_HEADER);
    content.push('\n');

    for alias in aliases {
        if !is_valid_alias_name(&alias.name) {
            log::warn!("Skipping alias with invalid name: {}", alias.name);
            continue;
        }
        let mut env_parts = Vec::new();
        // Always inject the three Anthropic vars (even if empty) to prevent
        // inheriting stale system environment variables.
        {
            let model = alias.anthropic_model.as_deref().unwrap_or("");
            env_parts.push(format!(
                "ANTHROPIC_MODEL='{}'",
                escape_zsh_single_quote(model)
            ));
        }
        {
            let token = alias.anthropic_auth_token.as_deref().unwrap_or("");
            env_parts.push(format!(
                "ANTHROPIC_AUTH_TOKEN='{}'",
                escape_zsh_single_quote(token)
            ));
        }
        {
            let url = alias.anthropic_base_url.as_deref().unwrap_or("");
            env_parts.push(format!(
                "ANTHROPIC_BASE_URL='{}'",
                escape_zsh_single_quote(url)
            ));
        }
        if let Some(ref custom_vars) = alias.custom_env_vars {
            for (k, v) in custom_vars {
                if !is_valid_env_key(k) {
                    log::warn!("Skipping custom env var with invalid key: {}", k);
                    continue;
                }
                if !v.is_empty() {
                    env_parts.push(format!("{}='{}'", k, escape_zsh_single_quote(v)));
                }
            }
        }
        // Use env -u CLAUDECODE to prevent "nested session" detection
        let func_body = if env_parts.is_empty() {
            "env -u CLAUDECODE claude \"$@\"".to_string()
        } else {
            format!(
                "env -u CLAUDECODE {} claude \"$@\"",
                env_parts.join(" ")
            )
        };
        content.push_str(&format!("{}() {{ {} }}\n", alias.name, func_body));
    }

    content
}

// --- Source line in profile ---

fn build_source_block() -> Result<String, String> {
    let aliases_path = get_aliases_file_path()?;
    let path_str = aliases_path.to_string_lossy();

    #[cfg(target_os = "windows")]
    let source_line = format!(". \"{}\"", path_str.replace('/', "\\"));

    #[cfg(target_os = "macos")]
    let source_line = format!("[ -f \"{}\" ] && source \"{}\"", path_str, path_str);

    Ok(format!("{}\n{}\n{}", MARKER_BEGIN, source_line, MARKER_END))
}

fn profile_contains_marker(content: &str) -> bool {
    content.contains(MARKER_BEGIN)
}

fn remove_marker_block(content: &str) -> String {
    let mut result = Vec::new();
    let mut inside_block = false;

    for line in content.lines() {
        if line.trim() == MARKER_BEGIN {
            inside_block = true;
            continue;
        }
        if line.trim() == MARKER_END {
            inside_block = false;
            continue;
        }
        if !inside_block {
            result.push(line);
        }
    }

    let mut text = result.join("\n");
    if !text.ends_with('\n') {
        text.push('\n');
    }
    text
}

// --- Core operations ---

fn write_aliases_file(aliases: &[crate::ClaudeAliasConfig]) -> Result<(), String> {
    let path = get_aliases_file_path()?;
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| format!("Failed to create directory: {}", e))?;
    }
    let content = generate_aliases_content(aliases);
    fs::write(&path, &content).map_err(|e| format!("Failed to write aliases file: {}", e))?;
    log::info!("Wrote system aliases file: {}", path.display());
    Ok(())
}

fn add_source_line_to_profile() -> Result<(), String> {
    let profile_path = get_shell_profile_path()?;

    if let Some(parent) = profile_path.parent() {
        fs::create_dir_all(parent)
            .map_err(|e| format!("Failed to create profile directory: {}", e))?;
    }

    let content = if profile_path.exists() {
        fs::read_to_string(&profile_path)
            .map_err(|e| format!("Failed to read profile: {}", e))?
    } else {
        String::new()
    };

    let source_block = build_source_block()?;

    if profile_contains_marker(&content) {
        // Replace existing block
        let cleaned = remove_marker_block(&content);
        let new_content = format!("{}\n{}\n", cleaned.trim_end(), source_block);
        fs::write(&profile_path, &new_content)
            .map_err(|e| format!("Failed to write profile: {}", e))?;
    } else {
        // Append
        let mut new_content = content;
        if !new_content.ends_with('\n') && !new_content.is_empty() {
            new_content.push('\n');
        }
        new_content.push('\n');
        new_content.push_str(&source_block);
        new_content.push('\n');
        fs::write(&profile_path, &new_content)
            .map_err(|e| format!("Failed to write profile: {}", e))?;
    }

    log::info!(
        "Added source line to profile: {}",
        profile_path.display()
    );
    Ok(())
}

fn remove_source_line_from_profile() -> Result<(), String> {
    let profile_path = get_shell_profile_path()?;

    if !profile_path.exists() {
        return Ok(());
    }

    let content = fs::read_to_string(&profile_path)
        .map_err(|e| format!("Failed to read profile: {}", e))?;

    if !profile_contains_marker(&content) {
        return Ok(());
    }

    let new_content = remove_marker_block(&content);
    fs::write(&profile_path, &new_content)
        .map_err(|e| format!("Failed to write profile: {}", e))?;

    log::info!(
        "Removed source line from profile: {}",
        profile_path.display()
    );
    Ok(())
}

fn check_registration_status() -> Result<SystemAliasesStatus, String> {
    let aliases_path = get_aliases_file_path()?;
    let profile_path = get_shell_profile_path()?;

    let file_exists = aliases_path.exists();

    let profile_has_source = if profile_path.exists() {
        let content = fs::read_to_string(&profile_path)
            .map_err(|e| format!("Failed to read profile: {}", e))?;
        profile_contains_marker(&content)
    } else {
        false
    };

    Ok(SystemAliasesStatus {
        registered: file_exists && profile_has_source,
        file_exists,
        profile_has_source,
        aliases_file_path: aliases_path.to_string_lossy().to_string(),
        profile_path: profile_path.to_string_lossy().to_string(),
    })
}

// --- Tauri commands ---

#[tauri::command]
pub fn check_system_aliases_status() -> Result<SystemAliasesStatus, String> {
    check_registration_status()
}

#[tauri::command]
pub fn register_system_aliases(
    aliases: Vec<crate::ClaudeAliasConfig>,
) -> Result<(), String> {
    if aliases.is_empty() {
        return Err("No aliases to register".to_string());
    }
    write_aliases_file(&aliases)?;
    add_source_line_to_profile()?;
    Ok(())
}

#[tauri::command]
pub fn unregister_system_aliases() -> Result<(), String> {
    remove_source_line_from_profile()?;
    let path = get_aliases_file_path()?;
    if path.exists() {
        fs::remove_file(&path)
            .map_err(|e| format!("Failed to delete aliases file: {}", e))?;
    }
    log::info!("System aliases unregistered");
    Ok(())
}
